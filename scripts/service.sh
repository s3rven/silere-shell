#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
case "$ROOT" in *$'\n'*|*$'\r'*) echo 'The checkout path cannot contain a newline.' >&2; exit 1 ;; esac
source "$ROOT/scripts/lib/xdg.sh"
source "$ROOT/scripts/lib/unit.sh"

config_home="$(_silere_xdg_home "${XDG_CONFIG_HOME:-}" .config)"
unit="$config_home/systemd/user/silere-shell.service"

render_unit() {
    local launcher line
    launcher="$(_silere_unit_exec_quote "$ROOT/scripts/silere")"
    while IFS= read -r line; do
        if [[ "$line" = ExecStart=* ]]; then printf 'ExecStart=%s run\n' "$launcher"
        else printf '%s\n' "$line"; fi
    done < "$ROOT/scripts/silere-shell.service"
}

case "${1:-status}" in
    install)
        if [ "${2:-}" = --dry-run ] && [ "$#" -eq 2 ]; then render_unit; exit 0; fi
        [ "$#" -eq 1 ] || exit 2
        if [ -e "$unit" ] || [ -L "$unit" ]; then
            if [ -L "$unit" ] || ! grep -qx '# generated by silere-shell' "$unit"; then
                echo 'Refusing to replace an unmanaged shell service.' >&2
                exit 1
            fi
            _silere_unit_runs_checkout "$ROOT" \
                || { echo 'This service belongs to another Silere installation.' >&2; exit 1; }
        fi
        mkdir -p -- "${unit%/*}"
        temp_unit="$(mktemp "${unit%/*}/.silere-service.XXXXXX")"
        trap 'rm -f -- "$temp_unit"' EXIT
        render_unit > "$temp_unit"
        chmod 0644 "$temp_unit"
        mv -- "$temp_unit" "$unit"
        systemctl --user daemon-reload
        printf '%s\n' 'Installed the optional shell service.' \
            'Use silere run --supervised --startup as your sole compositor startup command.' \
            'Replace the existing silere run --startup command; the service has not been started or enabled.'
        ;;
    start)
        [ "$#" -eq 1 ] || exit 2
        _silere_unit_runs_checkout "$ROOT" \
            || { echo 'Run silere service install for this checkout first.' >&2; exit 1; }
        # preserve the environment of an already running owner
        if ! systemctl --user is-active --quiet silere-shell.service; then
            names=()
            session_names=(WAYLAND_DISPLAY DISPLAY XDG_CURRENT_DESKTOP XDG_SESSION_TYPE XDG_SESSION_ID \
                HYPRLAND_INSTANCE_SIGNATURE NIRI_SOCKET DBUS_SESSION_BUS_ADDRESS)
            for name in "${session_names[@]}" PATH LANG LANGUAGE LC_ALL LC_CTYPE LC_NUMERIC \
                LC_TIME LC_COLLATE LC_MONETARY LC_MESSAGES LC_PAPER LC_NAME LC_ADDRESS \
                LC_TELEPHONE LC_MEASUREMENT LC_IDENTIFICATION; do
                [ -z "${!name:-}" ] || names+=("$name")
            done
            [ -n "${WAYLAND_DISPLAY:-}" ] || { echo 'Start the supervised shell inside your Wayland session.' >&2; exit 1; }
            systemctl --user unset-environment "${session_names[@]}" LANGUAGE LC_ALL LC_CTYPE LC_NUMERIC \
                LC_TIME LC_COLLATE LC_MONETARY LC_MESSAGES LC_PAPER LC_NAME LC_ADDRESS \
                LC_TELEPHONE LC_MEASUREMENT LC_IDENTIFICATION
            systemctl --user import-environment "${names[@]}"
            systemctl --user reset-failed silere-shell.service
        fi
        systemctl --user start silere-shell.service
        ;;
    status)
        [ "$#" -le 1 ] || exit 2
        systemctl --user status --no-pager silere-shell.service
        ;;
    remove)
        [ "$#" -eq 1 ] || exit 2
        if [ ! -f "$unit" ] || [ -L "$unit" ] || ! grep -qx '# generated by silere-shell' "$unit" \
                || ! _silere_unit_runs_checkout "$ROOT"; then
            echo 'No service owned by this installation was found.' >&2
            exit 1
        fi
        systemctl --user disable --now silere-shell.service
        rm -- "$unit"
        systemctl --user daemon-reload
        ;;
    *) echo 'Usage: silere service install [--dry-run]|status|remove' >&2; exit 2 ;;
esac
